bool loadOccupancyGridFromYaml(const std::string& yaml_path,
                               nav_msgs::OccupancyGrid& grid,
                               std::string& error) {
  std::ifstream file(yaml_path);
  if (!file) {
    error = "cannot open map yaml: " + yaml_path;
    return false;
  }

  std::string image_name;
  double resolution = 0.0;
  double origin_x = 0.0, origin_y = 0.0, origin_yaw = 0.0;
  bool negate = false;
  double occupied_thresh = 0.65;
  double free_thresh = 0.196;
  bool has_resolution = false;
  bool has_origin = false;

  std::string line;
  while (std::getline(file, line)) {
    const std::string cleaned = trim(stripComment(line));
    if (cleaned.empty()) continue;
    const std::size_t colon = cleaned.find(':');
    if (colon == std::string::npos) continue;
    const std::string key = trim(cleaned.substr(0, colon));
    const std::string value = trim(cleaned.substr(colon + 1));
    if (key == "image") {
      image_name = value;
    } else if (key == "resolution") {
      has_resolution = parseDouble(value, resolution);
    } else if (key == "origin") {
      has_origin = parseOriginList(value, origin_x, origin_y, origin_yaw);
    } else if (key == "negate") {
      negate = (std::atoi(value.c_str()) != 0);
    } else if (key == "occupied_thresh") {
      parseDouble(value, occupied_thresh);
    } else if (key == "free_thresh") {
      parseDouble(value, free_thresh);
    }
  }

  if (image_name.empty()) {
    error = "map yaml has no 'image' key: " + yaml_path;
    return false;
  }
  if (!has_resolution || resolution <= 0.0) {
    error = "map yaml has an invalid 'resolution': " + yaml_path;
    return false;
  }
  if (!has_origin) {
    error = "map yaml has an invalid 'origin': " + yaml_path;
    return false;
  }

  std::string image_path = image_name;
  if (!image_path.empty() && image_path.front() != '/') {
    const std::size_t slash = yaml_path.find_last_of('/');
    const std::string dir =
        slash == std::string::npos ? "" : yaml_path.substr(0, slash + 1);
    image_path = dir + image_path;
  }

  PgmImage image;
  if (!readPgm(image_path, image, error)) return false;

  grid.header.frame_id = "map";
  grid.header.stamp = ros::Time::now();
  grid.info.resolution = static_cast<float>(resolution);
  grid.info.width = static_cast<uint32_t>(image.width);
  grid.info.height = static_cast<uint32_t>(image.height);
  grid.info.origin.position.x = origin_x;
  grid.info.origin.position.y = origin_y;
  grid.info.origin.position.z = 0.0;
  // yaw only: qz = sin(yaw/2), qw = cos(yaw/2)
  grid.info.origin.orientation.x = 0.0;
  grid.info.origin.orientation.y = 0.0;
  grid.info.origin.orientation.z = std::sin(origin_yaw * 0.5);
  grid.info.origin.orientation.w = std::cos(origin_yaw * 0.5);

  const std::size_t count = static_cast<std::size_t>(image.width) *
                            static_cast<std::size_t>(image.height);
  grid.data.assign(count, -1);
  for (int y = 0; y < image.height; ++y) {
    // PGM rows run top-down; OccupancyGrid rows run bottom-up.
    const int src_row = image.height - 1 - y;
    for (int x = 0; x < image.width; ++x) {
      const unsigned char pixel =
          image.pixels[static_cast<std::size_t>(src_row) * image.width + x];
      const double shade = static_cast<double>(pixel) /
                           static_cast<double>(image.max_value);
      const double occupancy = negate ? shade : (1.0 - shade);
      int8_t cell = -1;
      if (occupancy > occupied_thresh) {
        cell = 100;
      } else if (occupancy < free_thresh) {
        cell = 0;
      }
      grid.data[static_cast<std::size_t>(y) * image.width + x] = cell;
    }
  }
  return true;
}

