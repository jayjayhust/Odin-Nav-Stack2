struct PgmImage {
  int width{0};
  int height{0};
  int max_value{255};
  std::vector<unsigned char> pixels;
};

std::string trim(const std::string& value) {
  const std::size_t begin = value.find_first_not_of(" \t\r\n");
  if (begin == std::string::npos) return "";
  const std::size_t end = value.find_last_not_of(" \t\r\n");
  return value.substr(begin, end - begin + 1);
}

std::string stripComment(const std::string& line) {
  // YAML comments start at '#' only when not inside quotes. Map YAML files
  // generated by pcd_to_pgm.py never quote '#', so a plain find is sufficient.
  const std::size_t pos = line.find('#');
  return pos == std::string::npos ? line : line.substr(0, pos);
}

bool parseDouble(const std::string& text, double& out) {
  std::string value = trim(text);
  if (value.empty()) return false;
  char* end = nullptr;
  out = std::strtod(value.c_str(), &end);
  return end != nullptr && *end == '\0';
}

bool parseOriginList(const std::string& text, double& x, double& y, double& yaw) {
  std::string value = trim(text);
  if (value.size() < 2) return false;
  if (value.front() == '[') value.erase(value.begin());
  if (!value.empty() && value.back() == ']') value.pop_back();
  for (char& c : value) {
    if (c == ',' || c == '[' || c == ']') c = ' ';
  }
  std::istringstream stream(value);
  std::vector<double> numbers;
  double number = 0.0;
  while (stream >> number) numbers.push_back(number);
  if (numbers.size() < 2) return false;
  x = numbers[0];
  y = numbers[1];
  yaw = numbers.size() >= 3 ? numbers[2] : 0.0;
  return true;
}

// PGM parser that understands '#' comments and both P2 (ASCII) / P5 (binary).
bool readPgm(const std::string& path, PgmImage& image, std::string& error) {
  std::ifstream file(path, std::ios::binary);
  if (!file) {
    error = "cannot open pgm: " + path;
    return false;
  }
  std::string magic;
  file >> magic;
  if (magic != "P5" && magic != "P2") {
    error = "unsupported pgm magic '" + magic + "' (expected P5 or P2): " + path;
    return false;
  }

  // Header integers may be separated by comments/whitespace.
  auto nextInt = [&file](int& out) -> bool {
    char c = 0;
    while (file.get(c)) {
      if (c == '#') {
        std::string ignored;
        std::getline(file, ignored);
        continue;
      }
      if (std::isspace(static_cast<unsigned char>(c))) continue;
      file.unget();
      break;
    }
    file >> out;
    return !file.fail();
  };

  int width = 0, height = 0, max_value = 0;
  if (!nextInt(width) || !nextInt(height) || !nextInt(max_value)) {
    error = "invalid pgm header: " + path;
    return false;
  }
  if (width <= 0 || height <= 0) {
    error = "invalid pgm dimensions: " + path;
    return false;
  }
  if (max_value <= 0 || max_value > 255) {
    error = "unsupported pgm maxval (only 8-bit pgm is supported): " + path;
    return false;
  }

  const std::size_t count = static_cast<std::size_t>(width) *
                            static_cast<std::size_t>(height);
  image.width = width;
  image.height = height;
  image.max_value = max_value;
  image.pixels.assign(count, 0);

  if (magic == "P5") {
    // Exactly one whitespace byte separates the header from the raster.
    char separator = 0;
    file.get(separator);
    if (!std::isspace(static_cast<unsigned char>(separator))) {
      error = "malformed pgm header (missing separator): " + path;
      return false;
    }
    file.read(reinterpret_cast<char*>(image.pixels.data()),
              static_cast<std::streamsize>(count));
    if (!file) {
      error = "truncated pgm raster: " + path;
      return false;
    }
  } else {
    for (std::size_t i = 0; i < count; ++i) {
      int sample = 0;
      if (!(file >> sample)) {
        error = "truncated ASCII pgm raster: " + path;
        return false;
      }
      image.pixels[i] = static_cast<unsigned char>(
          std::max(0, std::min(max_value, sample)));
    }
  }
  return true;
}

